export const SOLUTION_PROGRESS_KEY = 'strateg-solution-progress';

export function getStepsByModule(moduleId: string): SolutionStep[] {
  return SOLUTION_STEPS.filter((step) => step.moduleId === moduleId);
}

export function getCompletedSolutionStepIds(): string[] {
  try {
    const raw = localStorage.getItem(SOLUTION_PROGRESS_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.filter((id): id is string => typeof id === 'string') : [];
  } catch {
    return [];
  }
}